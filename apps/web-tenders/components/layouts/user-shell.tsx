import { AppSidebar } from "@/components/app-sidebar"
import { SiteHeader } from "@/components/site-header"
import { SidebarInset, SidebarProvider } from "@/components/ui/sidebar"

/**
 * The authenticated app chrome (sidebar + header). Does not gate on auth —
 * wrap it in `AuthGuard` for protected routes, or render it directly (e.g. from
 * `SharedLayoutClient`) to show the shell to already-authenticated users on
 * otherwise-public pages.
 */
export function UserShell({ children }: { children: React.ReactNode }) {
  return (
    <SidebarProvider
      style={
        {
          "--sidebar-width": "calc(var(--spacing) * 72)",
          "--header-height": "calc(var(--spacing) * 12)",
        } as React.CSSProperties
      }
    >
      <AppSidebar variant="inset" />
      <SidebarInset>
        <SiteHeader />
        {children}
      </SidebarInset>
    </SidebarProvider>
  )
}
